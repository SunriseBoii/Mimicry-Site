await page.goto('http://127.0.0.1:3000/?review=ps05&transport=retry');
await page.waitForSelector('[data-ps05]',{timeout:120000});await page.waitForTimeout(3500);
await page.screenshot({path:`${dir}/hero.png`});
console.log('hero',await page.locator('[data-ps05]').getAttribute('data-reading'));
